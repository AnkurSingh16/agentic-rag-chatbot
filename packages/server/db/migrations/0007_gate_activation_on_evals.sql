-- Enforces the eval gate in the database (ADR 0002) and records every activation. Before this, the
-- gate lived only in ragctl, so any caller holding the ingest credential could activate an
-- unevaluated version by calling the function directly.

-- One row per activation, forced or not. There is no foreign key to index_versions: training
-- prunes old versions, and the record of what was served, by whom and why must outlive them.
CREATE TABLE rag.activation_log (
  -- BY DEFAULT rather than ALWAYS is safe: no role has an INSERT or UPDATE grant on id.
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instance_id text NOT NULL REFERENCES rag.instances (id),
  index_version_id uuid NOT NULL,
  forced boolean NOT NULL,
  reason text CHECK (length(reason) BETWEEN 1 AND 1000),
  operator text NOT NULL CHECK (length(operator) BETWEEN 1 AND 128),
  activated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT forced OR reason IS NOT NULL)
);

CREATE INDEX activation_log_instance ON rag.activation_log (instance_id, activated_at);

ALTER TABLE rag.activation_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE rag.activation_log FORCE ROW LEVEL SECURITY;

CREATE POLICY activation_log_ingest_select ON rag.activation_log FOR SELECT TO rag_ingest
  USING (instance_id = rag.current_instance());
CREATE POLICY activation_log_ingest_insert ON rag.activation_log FOR INSERT TO rag_ingest
  WITH CHECK (instance_id = rag.current_instance());

GRANT SELECT ON rag.activation_log TO rag_ingest;
-- activated_at always comes from the default, so a log row cannot be backdated.
GRANT INSERT (instance_id, index_version_id, forced, reason, operator) ON rag.activation_log
  TO rag_ingest;

-- The activation function runs as rag_migrator, which forced RLS also restricts. These policies
-- let it read the caller's eval runs and write the caller's log rows, and nothing else.
CREATE POLICY eval_runs_activation ON rag.eval_runs FOR SELECT TO rag_migrator
  USING (instance_id = rag.current_instance());
CREATE POLICY activation_log_activation_select ON rag.activation_log FOR SELECT TO rag_migrator
  USING (instance_id = rag.current_instance());
CREATE POLICY activation_log_activation_insert ON rag.activation_log FOR INSERT TO rag_migrator
  WITH CHECK (instance_id = rag.current_instance());

-- The old signature has no gate. Dropping it leaves no way to activate without one.
DROP FUNCTION rag.activate_index_version(text, uuid);

-- Makes a ready version active, or a retired one again for rollback (ADR 0002). Without p_force,
-- the version's latest eval run must have passed with the version's own embedding provider and
-- model. With p_force, p_reason must explain why. Every activation is logged with p_operator.
-- The previous active version becomes retired. Returns the previously active version, or NULL.
CREATE FUNCTION rag.activate_index_version(
  p_instance_id text,
  p_version_id uuid,
  p_force boolean,
  p_reason text,
  p_operator text
) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, rag, pg_temp AS $$
DECLARE
  v_status text;
  v_provider text;
  v_model text;
  v_previous uuid;
  v_reason text := NULLIF(btrim(p_reason), '');
  v_operator text := NULLIF(btrim(p_operator), '');
  v_eval record;
BEGIN
  IF p_instance_id IS DISTINCT FROM rag.current_instance() THEN
    RAISE EXCEPTION 'activation requires a matching instance context' USING ERRCODE = '42501';
  END IF;
  IF p_force IS NULL THEN
    RAISE EXCEPTION 'p_force must be true or false' USING ERRCODE = '22023';
  END IF;
  IF v_operator IS NULL THEN
    RAISE EXCEPTION 'activation requires an operator' USING ERRCODE = '22023';
  END IF;
  IF p_force AND v_reason IS NULL THEN
    RAISE EXCEPTION 'forced activation requires a reason' USING ERRCODE = '22023';
  END IF;

  -- Locking the instance row serialises concurrent activations of the same instance.
  SELECT active_index_version_id INTO v_previous
    FROM rag.instances WHERE id = p_instance_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'instance does not exist' USING ERRCODE = 'P0002';
  END IF;

  SELECT status, embedding_provider, embedding_model INTO v_status, v_provider, v_model
    FROM rag.index_versions WHERE id = p_version_id AND instance_id = p_instance_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'index version does not exist for this instance' USING ERRCODE = 'P0002';
  END IF;
  IF v_status NOT IN ('ready', 'retired') THEN
    RAISE EXCEPTION 'index version is %, expected ready or retired', v_status
      USING ERRCODE = '55000';
  END IF;

  IF NOT p_force THEN
    -- Same ordering as the latest eval run that ragctl versions shows.
    SELECT id, passed, embedding_provider, embedding_model INTO v_eval
      FROM rag.eval_runs
      WHERE instance_id = p_instance_id AND index_version_id = p_version_id
      ORDER BY created_at DESC, id DESC
      LIMIT 1;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'eval gate: index version has no eval run' USING ERRCODE = '55000';
    END IF;
    IF NOT v_eval.passed THEN
      RAISE EXCEPTION 'eval gate: latest eval run % failed', v_eval.id USING ERRCODE = '55000';
    END IF;
    IF v_eval.embedding_provider <> v_provider OR v_eval.embedding_model <> v_model THEN
      RAISE EXCEPTION 'eval gate: latest eval run used %/%, but the version was built with %/%',
        v_eval.embedding_provider, v_eval.embedding_model, v_provider, v_model
        USING ERRCODE = '55000';
    END IF;
  END IF;

  UPDATE rag.index_versions SET status = 'retired'
    WHERE instance_id = p_instance_id AND status = 'active';
  UPDATE rag.index_versions SET status = 'active', activated_at = now()
    WHERE id = p_version_id;
  UPDATE rag.instances SET active_index_version_id = p_version_id
    WHERE id = p_instance_id;
  INSERT INTO rag.activation_log (instance_id, index_version_id, forced, reason, operator)
    VALUES (p_instance_id, p_version_id, p_force, v_reason, v_operator);

  RETURN v_previous;
END;
$$;

REVOKE ALL ON FUNCTION rag.activate_index_version(text, uuid, boolean, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION rag.activate_index_version(text, uuid, boolean, text, text) TO rag_ingest;
